import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

const generatedPath = (root: string) => resolve(root, 'jobs', 'registry.generated.ts');

export const generateJobRegistry = (root = process.cwd()): string[] => {
  const jobsRoot = resolve(root, 'jobs');
  const ids = readdirSync(jobsRoot, {withFileTypes: true})
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const missing = ids.filter((id) => !['brand.json', 'spec.json', 'scenes/index.tsx'].every((file) => {
    try {
      readFileSync(resolve(jobsRoot, id, file));
      return true;
    } catch {
      return false;
    }
  }));
  if (missing.length > 0) throw new Error(`Incomplete job fixture(s): ${missing.join(', ')}`);
  const imports = ids.flatMap((id, index) => [
    `import brand${index} from './${id}/brand.json';`,
    `import spec${index} from './${id}/spec.json';`,
    `import {default as scene${index}} from './${id}/scenes';`,
  ]).join('\n');
  const entries = ids.map((id, index) => `  '${id}': {id: '${id}', brand: brand${index} as BrandJson, spec: spec${index} as AdSpec, renderScene: scene${index}},`).join('\n');
  const output = `// Generated by scripts/generate-job-registry.ts. Do not edit.\nimport type {AdSpec, BrandJson, SceneRenderer} from '../engine';\n${imports}\n\ntype GeneratedJobDefinition = {id: string; brand: BrandJson; spec: AdSpec; renderScene: SceneRenderer};\n\nexport const generatedJobs: Record<string, GeneratedJobDefinition> = {\n${entries}\n};\n`;
  const path = generatedPath(root);
  const current = (() => { try { return readFileSync(path, 'utf8'); } catch { return ''; } })();
  if (current !== output) writeFileSync(path, output);
  return ids;
};
