import os
import sys
import time
import urllib.parse
import urllib.request
from playwright.sync_api import sync_playwright
from colorama import Fore, init

sys.stdout.reconfigure(encoding='utf-8')
init(autoreset=True)

def fetch_ui_workflow_images(app_name, search_queries):
    """
    Acts as the AI UI Researcher. Navigates to Google Images, searches for the exact UI screens, 
    and downloads the best high-res mockup for each step of the workflow.
    """
    print(f"\n{Fore.MAGENTA}===================================================={Fore.RESET}")
    print(f"{Fore.MAGENTA}🔎 UI RESEARCHER: Sourcing Start-to-End Workflow for '{app_name}'{Fore.RESET}")
    print(f"{Fore.MAGENTA}===================================================={Fore.RESET}\n")
    
    ui_assets_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "input", "ui_assets")
    os.makedirs(ui_assets_dir, exist_ok=True)
    
    downloaded_paths = []
    
    with sync_playwright() as p:
        # Launching hidden browser (can set headless=False for debugging)
        browser = p.chromium.launch(headless=True)
        page = browser.new_page(user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")
        
        for i, query in enumerate(search_queries):
            scene_id = i + 1
            print(f"{Fore.YELLOW}🎬 Researching Scene {scene_id} UI: '{query}'{Fore.RESET}")
            
            try:
                # URL encode the search query for Google Images
                encoded_query = urllib.parse.quote(query)
                search_url = f"https://www.google.com/search?tbm=isch&q={encoded_query}"
                
                page.goto(search_url, wait_until="domcontentloaded")
                page.wait_for_timeout(2000) # Give images time to load
                
                # Click the first image thumbnail to open the large preview pane
                thumbnails = page.locator('div[role="listitem"] img')
                thumbnails.first.click()
                
                page.wait_for_timeout(2000) # Wait for high-res image to load in pane
                
                # Google images large preview is usually an img tag with no width/height attributes or inside an <a> tag
                # We target the large image by looking for the one that has a src starting with http and is currently visible in the right pane
                large_image = page.locator('img.sFlh5c, img.n3VNCb, img.iPVvYb').first
                
                img_url = None
                if large_image.count() > 0:
                    img_url = large_image.get_attribute("src")
                else:
                    # Fallback to thumbnail if high-res pane fails
                    print(f"{Fore.YELLOW}   -> Could not find high-res pane, falling back to thumbnail.{Fore.RESET}")
                    img_url = thumbnails.first.get_attribute("src")
                
                if img_url and img_url.startswith('http'):
                    filename = f"{app_name.lower().replace(' ', '_')}_scene_{scene_id}.jpg"
                    filepath = os.path.join(ui_assets_dir, filename)
                    
                    # Download the image
                    urllib.request.urlretrieve(img_url, filepath)
                    print(f"{Fore.GREEN}   -> ✅ Successfully captured UI and saved to {filename}{Fore.RESET}")
                    downloaded_paths.append(filepath)
                else:
                    print(f"{Fore.RED}   -> ❌ Failed to extract a valid image URL.{Fore.RESET}")
                    
            except Exception as e:
                print(f"{Fore.RED}   -> ❌ Error scraping image: {e}{Fore.RESET}")
                
        browser.close()
        
    return downloaded_paths

if __name__ == "__main__":
    app = sys.argv[1] if len(sys.argv) > 1 else "Swiggy"
    # Example autonomous queries generated by the Brain
    mock_queries = [
        f"{app} app home screen mobile UI dribbble",
        f"{app} app search food menu mobile UI dribbble",
        f"{app} app order tracking map mobile UI dribbble"
    ]
    fetch_ui_workflow_images(app, mock_queries)
