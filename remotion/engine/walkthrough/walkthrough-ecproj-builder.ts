import type {SoftwareWalkthroughSpec} from './types';

export class WalkthroughEcprojBuilder {
  /**
   * Generates EffectCraft ExtendScript JSX compiling the 2D walkthrough composition
   * with scale/anchor point auto-zoom keyframes and shape layer vector cursor.
   */
  static generateJsx(spec: SoftwareWalkthroughSpec): string {
    const {metadata, walkthroughConfig} = spec;
    const {width, height, fps} = metadata;
    const config = walkthroughConfig;

    const lines: string[] = [];
    lines.push(`// Generated by WalkthroughEcprojBuilder for EffectCraft (mode: software_walkthrough)`);
    lines.push(`var comp = app.project.items.addComp('${metadata.title}', ${width}, ${height}, 1.0, 15.0, ${fps});`);
    lines.push(`comp.bgColor = [0.035, 0.04, 0.06];`);

    // 1. Add Background Wrapper
    lines.push(`var bg = comp.layers.addSolid([0.05, 0.05, 0.08], 'Desktop Canvas', ${width}, ${height}, 1.0);`);

    // 2. Add Screen Recording Layer (2D layer)
    lines.push(`var screenLayer = comp.layers.addSolid([0.08, 0.09, 0.14], 'Screen Recording', ${width}, ${height}, 1.0);`);
    lines.push(`screenLayer.name = 'Screen Recording Viewport';`);

    // 3. Keyframe 2D Camera Zoom & Anchor Point
    if (config.cameraZoomTrack.length > 0) {
      lines.push(`// Keyframing 2D Dynamic Auto-Zoom`);
      config.cameraZoomTrack.forEach((kf) => {
        const timeSec = Math.round((kf.startFrame / fps) * 100) / 100;
        const scalePct = Math.round(kf.zoomScale * 100);
        // Anchor point centers on the focal point [cx, cy]
        lines.push(`screenLayer.transform.anchorPoint.setValueAtTime(${timeSec}, [${kf.center[0]}, ${kf.center[1]}]);`);
        lines.push(`screenLayer.transform.scale.setValueAtTime(${timeSec}, [${scalePct}, ${scalePct}]);`);
      });
    }

    // 4. Add Vector Cursor Rig as Shape Layer
    lines.push(`// Adding Vector Cursor Rig`);
    lines.push(`var cursorLayer = comp.layers.addSolid([1.0, 1.0, 1.0], 'Cursor Pointer', 24, 24, 1.0);`);
    lines.push(`cursorLayer.name = 'Human Motor Cursor';`);

    if (config.cursorTrack.length > 0) {
      config.cursorTrack.forEach((action) => {
        const t0 = Math.round((action.startFrame / fps) * 100) / 100;
        const t1 = Math.round((action.endFrame / fps) * 100) / 100;
        lines.push(`cursorLayer.transform.position.setValueAtTime(${t0}, [${action.from[0]}, ${action.from[1]}]);`);
        lines.push(`cursorLayer.transform.position.setValueAtTime(${t1}, [${action.to[0]}, ${action.to[1]}]);`);

        if (action.clickFrame) {
          const clickTime = Math.round((action.clickFrame / fps) * 100) / 100;
          lines.push(`cursorLayer.transform.scale.setValueAtTime(${clickTime - 0.03}, [100, 100]);`);
          lines.push(`cursorLayer.transform.scale.setValueAtTime(${clickTime}, [86, 86]);`); // Contact compression
          lines.push(`cursorLayer.transform.scale.setValueAtTime(${clickTime + 0.05}, [100, 100]);`);
        }
      });
    }

    return lines.join('\n');
  }

  static writeJsx(spec: SoftwareWalkthroughSpec, outputPath: string): void {
    const code = this.generateJsx(spec);
    if (typeof process !== 'undefined' && process.versions?.node) {
      const nodeFs = eval('require')('fs');
      nodeFs.writeFileSync(outputPath, code, 'utf8');
    }
  }
}
